// Metinden şehir ismini parse et
export const parseCityFromText = (text) => {
  const lowerText = text.toLowerCase()
    .replace(/[şŞ]/g, 's')
    .replace(/[ıİ]/g, 'i')
    .replace(/[ğĞ]/g, 'g')
    .replace(/[üÜ]/g, 'u')
    .replace(/[öÖ]/g, 'o')
    .replace(/[çÇ]/g, 'c');
  
  // Şehir isimlerini kontrol et
  for (const [cityKey, cityData] of Object.entries(turkeyCities)) {
    if (lowerText.includes(cityKey)) {
      return cityData;
    }
  }
  
  // Varsayılan olarak İstanbul
  return { lat: 41.0082, lon: 28.9784, name: 'İstanbul' };
};

